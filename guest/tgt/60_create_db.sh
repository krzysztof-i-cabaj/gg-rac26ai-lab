#!/bin/bash
# ==============================================================================
# Tytul:        60_create_db.sh
# Opis:         Baza docelowa na ggtgt: listener LISTENER (TCP 1521), CDB single-instance tgtcdb
#               z PDB TGTPDB przez dbca -silent (plik rsp 600 z haslem tylko na czas dbca), potem
#               sql/03_tgt_prep_cdb.sql (parametr GG, FORCE LOGGING, SAVE STATE) i sql/05_demo_schema.sql
#               (te same tabele i wiersze startowe co na zrodle). Autostart przez oratab + systemd.
# Description [EN]: Target database on ggtgt: listener LISTENER (TCP 1521), single-instance CDB
#               tgtcdb with PDB TGTPDB via dbca -silent (600 rsp with the password only while dbca
#               runs), then sql/03_tgt_prep_cdb.sql (GG parameter, FORCE LOGGING, SAVE STATE) and
#               sql/05_demo_schema.sql (same tables and seed rows as the source). Autostart: oratab + systemd.
#
# Autor:        KCB Kris
# Data:         2026-11-16
# Wersja:       1.2 (oracle-db.service przez bash: SELinux / via bash for SELinux)
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - tgt/50_install_db.sh (oprogramowanie DB w DB_HOME)
# Requirements [EN]: - tgt/50_install_db.sh (DB software in DB_HOME)
#
# Uzycie [PL]:       bash /root/lab/tgt/60_create_db.sh   (lab.cmd tgt)
# Usage [EN]:        bash /root/lab/tgt/60_create_db.sh   (lab.cmd tgt)
# ==============================================================================
source /root/lab/lib.sh

RSP=$STAGE_DIR/dbca_tgt.rsp
LOG=$LOG_DIR/dbca_tgt.log
NET_ADMIN=$DB_HOME/network/admin

# --- 1. Listener (no Grid Infrastructure here: the listener is ours to run)
if write_if_changed "$NET_ADMIN/listener.ora" <<EOF
# Generated by 60_create_db.sh
LISTENER =
  (DESCRIPTION_LIST =
    (DESCRIPTION =
      (ADDRESS = (PROTOCOL = TCP)(HOST = ${NODE_NAME}.${LAB_DOMAIN})(PORT = 1521))
      (ADDRESS = (PROTOCOL = IPC)(KEY = EXTPROC1521))))
EOF
then
    run chown oracle:oinstall "$NET_ADMIN/listener.ora"
    as_user oracle "lsnrctl stop" >/dev/null 2>&1 || true
fi
as_user oracle "lsnrctl status" >/dev/null 2>&1 || as_user oracle "lsnrctl start"

# --- 2. Database
if grep -q "^${TGT_DB}:" /etc/oratab 2>/dev/null; then
    ok "database $TGT_DB already in /etc/oratab, dbca skipped"
else
    if [ -d "/u01/oradata/${TGT_DB^^}" ]; then
        cat >&2 <<EOF
/u01/oradata/${TGT_DB^^} exists but $TGT_DB is not in /etc/oratab: an earlier dbca stopped half way.
Nothing was removed. Read the log: ls -t $DB_BASE/cfgtoollogs/dbca/$TGT_DB/*.log | head -1
Then, as oracle: dbca -silent -deleteDatabase -sourceDB $TGT_DB
(if dbca refuses: as root, move /u01/oradata/${TGT_DB^^} away) and re-run lab.cmd tgt
EOF
        die "partial database $TGT_DB, see above"
    fi
    render_secret "$LAB_DIR/dbca_tgt.rsp" "$RSP" oracle
    log "dbca -silent -createDatabase $TGT_DB (single instance, 20-40 min; log: $LOG)"
    set +e
    as_user oracle "cd /tmp && dbca -silent -createDatabase -responseFile $RSP -ignorePreReqs" 2>&1 | tee "$LOG"
    rc=${PIPESTATUS[0]}
    set -e
    run rm -f "$RSP"
    check_rc "$rc" "dbca -createDatabase $TGT_DB"
fi

# --- 3. Autostart after a VM restart: oratab Y + dbstart from systemd
# SELinux enforcing: the Oracle home is default_t, systemd may not exec dbstart (203/EXEC Permission denied,
# 16.11); bash reads the script, the database then runs unconfined like a login shell start
run sed -i -E "s|^(${TGT_DB}:[^:]+):N|\1:Y|" /etc/oratab
if write_if_changed /etc/systemd/system/oracle-db.service <<EOF
# Generated by 60_create_db.sh: starts the listener and the oratab=Y databases of $DB_HOME
[Unit]
Description=Oracle Database ($TGT_DB) and listener
After=network-online.target
Wants=network-online.target

[Service]
Type=forking
User=oracle
Group=oinstall
ExecStart=/usr/bin/bash $DB_HOME/bin/dbstart $DB_HOME
ExecStop=/usr/bin/bash $DB_HOME/bin/dbshut $DB_HOME
RemainAfterExit=yes
TimeoutSec=600
LimitMEMLOCK=infinity
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF
then
    run systemctl daemon-reload
fi
run systemctl enable oracle-db.service
# Started by dbca now; the unit takes over from the next boot
as_user oracle "echo 'select status from v\$instance;' | sqlplus -S / as sysdba" | grep -q OPEN || run systemctl start oracle-db.service

# A dbca that failed late leaves no (or a closed) PDB: stop with what to do
pdb_ready "$TGT_PDB" || {
    cat >&2 <<EOF
$TGT_DB is in /etc/oratab but $TGT_PDB is not open READ WRITE: dbca stopped before the end.
Nothing was removed. Read the log: ls -t $DB_BASE/cfgtoollogs/dbca/$TGT_DB/*.log | head -1
Then, as oracle: dbca -silent -deleteDatabase -sourceDB $TGT_DB and re-run lab.cmd tgt
EOF
    die "$TGT_PDB not open, see above"
}

# --- 4. CDB settings and the demo schema (same seed rows as the source: no initial load)
log "sql/03_tgt_prep_cdb.sql (GG parameter, FORCE LOGGING, $TGT_PDB SAVE STATE)"
sysdba_file "$LAB_DIR/sql/03_tgt_prep_cdb.sql" "$TGT_PDB"
log "demo schemas HR, SALES in $TGT_PDB (sql/05_demo_schema.sql)"
sysdba_file "$LAB_DIR/sql/05_demo_schema.sql" "$TGT_PDB"
mark_done tgt_db
ok "target CDB $TGT_DB ready"
