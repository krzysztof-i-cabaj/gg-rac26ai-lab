#!/bin/bash
# ==============================================================================
# Tytul:        10_os_prereq.sh
# Opis:         Przygotowanie i kontrola ggtgt przed instalacja bazy: resolver tylko na gginfra,
#               chrony jako klient gginfra, avahi wylaczony; potem kontrole (nazwy RAC, SCAN
#               i oggvip z DNS, ping wezlow RAC, preinstall, THP, HugePages, RAM, miejsce na
#               /u01). Powtarzalny; konczy sie bledem przy FAIL.
# Description [EN]: Prepares and checks ggtgt before the database install: resolver on gginfra
#               only, chrony as a gginfra client, avahi off; then checks (RAC names, SCAN and
#               oggvip from DNS, ping to RAC nodes, preinstall, THP, HugePages, RAM, /u01 space).
#               Re-runnable; fails on any FAIL.
#
# Autor:        KCB Kris
# Data:         2026-11-15
# Wersja:       1.3 (bez firewalld / no firewalld; THP madvise)
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - kickstart role-tgt, gginfra po lab.cmd infra
# Requirements [EN]: - role-tgt kickstart, gginfra after lab.cmd infra
#
# Uzycie [PL]:       lab.cmd tgt   (recznie: bash /root/lab/tgt/10_os_prereq.sh)
# Usage [EN]:        lab.cmd tgt   (manual: bash /root/lab/tgt/10_os_prereq.sh)
# ==============================================================================
source /root/lab/lib.sh

log "resolver -> $INFRA_IP (NetworkManager dns=none, set by the kickstart; re-asserted here)"
write_if_changed /etc/NetworkManager/conf.d/90-lab-dns.conf <<'EOF' && run systemctl reload NetworkManager || true
[main]
dns=none
EOF
[ -L /etc/resolv.conf ] && run rm -f /etc/resolv.conf
write_if_changed /etc/resolv.conf <<EOF || true
search ${LAB_DOMAIN}
nameserver ${INFRA_IP}
EOF

log "chrony -> $INFRA_IP only (same time source as the RAC nodes: lag measured across hosts)"
if write_if_changed /etc/chrony.d/lab-client.conf <<EOF
# Lab time source (generated by 10_os_prereq.sh)
server ${INFRA_IP} iburst
EOF
then
    run sed -i -E '/^(pool|server) /s/^/#/' /etc/chrony.conf
    grep -q '^include /etc/chrony.d/\*.conf' /etc/chrony.conf || run sh -c "echo 'include /etc/chrony.d/*.conf' >> /etc/chrony.conf"
    run systemctl restart chronyd
fi
systemctl is-active --quiet avahi-daemon 2>/dev/null && run systemctl disable --now avahi-daemon.socket avahi-daemon.service || true
# Lab on a host-only network: no firewalld (RAC interconnect, SCAN, DNS, NTP between the VMs).
if systemctl is-enabled --quiet firewalld 2>/dev/null || systemctl is-active --quiet firewalld 2>/dev/null; then
    run systemctl disable --now firewalld
fi

[ "$DRY_RUN" = "1" ] && exit 0
wait_until 60 "chrony synced to $INFRA_IP" sh -c "chronyc -n sources | grep -q '^\^\*.*${INFRA_IP}'"

check "DNS: PTR of ${NODE_IP}"                 sh -c "dig +short -x ${NODE_IP} | grep -q '^${NODE_NAME}\.${LAB_DOMAIN}\.$'"
check_eq "DNS: ${SCAN_NAME} = 3 addresses"     "3" sh -c "dig +short ${SCAN_NAME}.${LAB_DOMAIN} | wc -l"
check_eq "DNS: ${OGG_VIP_NAME} = ${OGG_VIP}"   "$OGG_VIP" dig +short "${OGG_VIP_NAME}.${LAB_DOMAIN}"
for n in $RAC_NODES; do check "ping public ${n}" ping -c1 -W2 "$n"; done
check "package oracle-ai-database-preinstall-26ai" rpm -q oracle-ai-database-preinstall-26ai
check "THP madvise"                            grep -q '\[madvise\]' /sys/kernel/mm/transparent_hugepage/enabled
check "firewalld off"                          sh -c "! systemctl is-active --quiet firewalld"
check "HugePages > 0"                          sh -c '[ "$(cat /proc/sys/vm/nr_hugepages)" -gt 0 ]'
check "RAM >= 5 GB"                            sh -c '[ "$(free -m | awk "/Mem/{print \$2}")" -ge 5000 ]'
check "/u01 free >= 30 GB (or DB already in)"  sh -c "grep -q 'LOC=\"$DB_HOME\"' $INVENTORY/ContentsXML/inventory.xml 2>/dev/null || [ \"\$(df -BG --output=avail /u01 | tail -1 | tr -dc 0-9)\" -ge 30 ]"
[ "$CHECK_FAILED" = "0" ] || die "OS prerequisites failed (CHECK FAIL above)"
mark_done tgt_prereq
log "OS ready"
