#!/bin/bash
# ==============================================================================
# Tytul:        86_oggca_source.sh
# Opis:         Deployment zrodlowy przez oggca.sh -silent: Service Manager ggsm01 i deployment
#               oggsource na ACFS, zintegrowane z XAG (MAA Task 6), potem tnsnames.ora w TNS_ADMIN
#               deploymentu z aliasem OGGSOURCE_PDB przez IPC do lokalnego listenera (serwis gg_srcpdb,
#               MAA Task 9). Wymaga ACFS i VIP oggvip na tym wezle. Gotowy deployment = pominiety.
# Description [EN]: Source deployment via oggca.sh -silent: Service Manager ggsm01 and deployment
#               oggsource on ACFS, integrated with XAG (MAA Task 6), then tnsnames.ora in the
#               deployment TNS_ADMIN with alias OGGSOURCE_PDB over IPC to the local listener (service
#               gg_srcpdb, MAA Task 9). Needs ACFS and VIP oggvip on this node. Existing = skipped.
#
# Autor:        KCB Kris
# Data:         2026-11-14
# Wersja:       1.0
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - 70_acfs.sh create, 80_install_ogg.sh, 85_install_xag.sh, 87_xag_register.sh vip
# Requirements [EN]: - 70_acfs.sh create, 80_install_ogg.sh, 85_install_xag.sh, 87_xag_register.sh vip
#
# Uzycie [PL]:       bash /root/lab/rac/86_oggca_source.sh   (ggrac1; lab.cmd xag)
# Usage [EN]:        bash /root/lab/rac/86_oggca_source.sh   (ggrac1; lab.cmd xag)
# ==============================================================================
source /root/lab/lib.sh

RSP=$STAGE_DIR/oggca_source.rsp
LOG=$LOG_DIR/oggca_source.log
TNS_DIR=$OGG_SRC_HOME/etc

if [ "$DRY_RUN" != "1" ]; then
    mountpoint -q "$OGG_DEPLOY_ROOT" || die "$OGG_DEPLOY_ROOT is not mounted here: srvctl start filesystem -volume $ACFS_VOLUME -diskgroup $ACFS_DG -node $NODE_NAME"
    ip -o addr | grep -q " $OGG_VIP/" || die "VIP $OGG_VIP is not on $NODE_NAME: crsctl start resource $OGG_VIP_NAME -n $NODE_NAME (87_xag_register.sh vip)"
fi

if [ -d "$OGG_SRC_HOME/etc/conf" ] && [ -d "$OGG_SM_HOME/etc/conf" ]; then
    ok "Service Manager $OGG_SM and deployment $OGG_SRC_DEPLOY exist on ACFS, oggca skipped"
elif [ -e "$OGG_SM_HOME" ] || [ -e "$OGG_SRC_HOME" ]; then
    cat >&2 <<EOF
$OGG_SM_HOME or $OGG_SRC_HOME exists without a complete deployment: an earlier oggca stopped half way.
Nothing was removed. Read: ls -t $OGG_HOME/cfgtoollogs/oggca/*.log | head -1
Then remove the deployment with oggca (as oracle, CONFIGURATION_OPTION=REMOVE in a copy of the rsp)
or move both directories away, and re-run lab.cmd xag.
EOF
    die "partial deployment, see above"
else
    render_secret "$LAB_DIR/oggca_source.rsp" "$RSP" oracle
    log "oggca.sh -silent: $OGG_SM + $OGG_SRC_DEPLOY (XAG-integrated; log: $LOG)"
    set +e
    as_user oracle "cd /tmp && $OGG_HOME/bin/oggca.sh -silent -responseFile $RSP" 2>&1 | tee "$LOG"
    rc=${PIPESTATUS[0]}
    set -e
    run rm -f "$RSP"
    check_rc "$rc" "oggca.sh $OGG_SRC_DEPLOY"
fi

# Same alias on every node: the file lives on ACFS and moves with the deployment
run mkdir -p "$TNS_DIR"
if write_if_changed "$TNS_DIR/tnsnames.ora" <<EOF
# Generated by 86_oggca_source.sh: per-PDB Extract through the node-local listener (MAA Task 9)
OGGSOURCE_PDB =
  (DESCRIPTION =
    (ADDRESS = (PROTOCOL = IPC)(KEY = LISTENER))
    (CONNECT_DATA = (SERVICE_NAME = ${GG_SERVICE})))
EOF
then run chown oracle:oinstall "$TNS_DIR/tnsnames.ora"; fi
mark_done oggca_source
ok "deployment $OGG_SRC_DEPLOY ready (start via XAG: 87_xag_register.sh add)"
