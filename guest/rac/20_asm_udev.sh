#!/bin/bash
# ==============================================================================
# Tytul:        20_asm_udev.sh
# Opis:         Regula udev dla dyskow wspoldzielonych ASM: dysk bez partycji o dokladnym rozmiarze
#               z ASM_DISKS (lab.env), dowiazanie /dev/oracleasm/<nazwa> po ID_SERIAL, wlasciciel
#               grid:asmdba 0660. Bez ASMFD. Powtarzalny (regula przepisywana tylko przy zmianie).
# Description [EN]: udev rule for the shared ASM disks: an unpartitioned disk with the exact size
#               from ASM_DISKS (lab.env), /dev/oracleasm/<name> symlink by ID_SERIAL, owner
#               grid:asmdba 0660. No ASMFD. Re-runnable (rule rewritten only when it changes).
#
# Autor:        KCB Kris
# Data:         2026-11-15
# Wersja:       1.1 (dyski ASM grid:asmdba, PRVF-9992 / ORA-15001)
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - dyski DATA1/FRA1 podpiete przez lab.cmd build (shareable, fixed)
# Requirements [EN]: - DATA1/FRA1 disks attached by lab.cmd build (shareable, fixed)
#
# Uzycie [PL]:       lab.cmd shared   (recznie: bash /root/lab/rac/20_asm_udev.sh, na obu wezlach)
# Usage [EN]:        lab.cmd shared   (manual: bash /root/lab/rac/20_asm_udev.sh, on both nodes)
# ==============================================================================
source /root/lab/lib.sh

RULES=/etc/udev/rules.d/99-oracle-asmdevices.rules
tmp=$(mktemp)
echo "# ${CLUSTER_NAME}: ASM disks by ID_SERIAL (generated by 20_asm_udev.sh)" > "$tmp"
for spec in $ASM_DISKS; do
    name=${spec%%:*}; mib=${spec##*:}
    bytes=$((mib * 1024 * 1024))
    dev=$(lsblk -dnbo NAME,SIZE,TYPE | awk -v b="$bytes" '$3=="disk" && $2==b && $1 ~ /^sd/ {print $1}')
    [ -n "$dev" ] || die "$name: no ${mib} MiB disk (attached by lab.cmd build?)"
    [ "$(echo "$dev" | wc -l)" -eq 1 ] || die "$name: several ${mib} MiB disks: $dev"
    [ "$(lsblk -no NAME "/dev/$dev" | wc -l)" -eq 1 ] || die "$name: /dev/$dev has partitions"
    serial=$(udevadm info --query=property --name="/dev/$dev" | sed -n 's/^ID_SERIAL=//p')
    [ -n "$serial" ] || die "$name: no ID_SERIAL for /dev/$dev"
    log "$name = /dev/$dev ($serial)"
    echo "KERNEL==\"sd*\", SUBSYSTEM==\"block\", ENV{DEVTYPE}==\"disk\", ENV{ID_SERIAL}==\"$serial\", SYMLINK+=\"oracleasm/$name\", OWNER=\"grid\", GROUP=\"asmdba\", MODE=\"0660\"" >> "$tmp"
done

if write_if_changed "$RULES" < "$tmp"; then
    run udevadm control --reload-rules
    run udevadm trigger --type=devices --action=change
    run udevadm settle
fi
rm -f "$tmp"
[ "$DRY_RUN" = "1" ] && exit 0
for spec in $ASM_DISKS; do
    name=${spec%%:*}
    real=$(readlink -f "/dev/oracleasm/$name") || die "/dev/oracleasm/$name not created"
    owner=$(stat -c '%U:%G %a' "$real")
    [ "$owner" = "grid:asmdba 660" ] || die "$real: $owner (expected grid:asmdba 660)"
    ok "/dev/oracleasm/$name -> $real ($owner)"
done
mark_done rac_udev
