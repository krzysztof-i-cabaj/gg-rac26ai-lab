#!/bin/bash
# ==============================================================================
# Tytul:        10_os_prereq.sh
# Opis:         Przygotowanie i kontrola systemu wezla RAC przed GI: resolver tylko na gginfra,
#               chrony jako klient gginfra, avahi wylaczony; potem kontrole (SCAN z DNS = 3 adresy,
#               sasiedzi po sieci publicznej i interconnect, preinstall, uzytkownicy, THP, HugePages,
#               blokada jadra, miejsce na /u01). Powtarzalny; konczy sie bledem przy FAIL.
# Description [EN]: Prepares and checks a RAC node before GI: resolver on gginfra only, chrony
#               as a gginfra client, avahi off; then checks (DNS SCAN = 3 addresses, peers on the
#               public network and interconnect, preinstall, users, THP, HugePages, kernel lock,
#               /u01 space). Re-runnable; fails on any FAIL.
#
# Autor:        KCB Kris
# Data:         2026-11-15
# Wersja:       1.3 (bez firewalld / no firewalld; THP madvise)
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - kickstart role-rac, gginfra po lab.cmd infra
# Requirements [EN]: - role-rac kickstart, gginfra after lab.cmd infra
#
# Uzycie [PL]:       lab.cmd prereq   (recznie: bash /root/lab/rac/10_os_prereq.sh)
# Usage [EN]:        lab.cmd prereq   (manual: bash /root/lab/rac/10_os_prereq.sh)
# ==============================================================================
source /root/lab/lib.sh

log "resolver -> $INFRA_IP (NetworkManager dns=none, set by the kickstart; re-asserted here)"
write_if_changed /etc/NetworkManager/conf.d/90-lab-dns.conf <<'EOF' && run systemctl reload NetworkManager || true
[main]
dns=none
EOF
[ -L /etc/resolv.conf ] && run rm -f /etc/resolv.conf
write_if_changed /etc/resolv.conf <<EOF || true
search ${LAB_DOMAIN}
nameserver ${INFRA_IP}
EOF

log "chrony -> $INFRA_IP only (one time source for CTSS and both nodes)"
if write_if_changed /etc/chrony.d/lab-client.conf <<EOF
# Lab time source (generated by 10_os_prereq.sh)
server ${INFRA_IP} iburst
EOF
then
    # Internet pools off: gginfra is the only source (its own line lives in chrony.d)
    run sed -i -E '/^(pool|server) /s/^/#/' /etc/chrony.conf
    grep -q '^include /etc/chrony.d/\*.conf' /etc/chrony.conf || run sh -c "echo 'include /etc/chrony.d/*.conf' >> /etc/chrony.conf"
    run systemctl restart chronyd
fi
systemctl is-active --quiet avahi-daemon 2>/dev/null && run systemctl disable --now avahi-daemon.socket avahi-daemon.service || true
# Lab on a host-only network: no firewalld (RAC interconnect, SCAN, DNS, NTP between the VMs).
if systemctl is-enabled --quiet firewalld 2>/dev/null || systemctl is-active --quiet firewalld 2>/dev/null; then
    run systemctl disable --now firewalld
fi

[ "$DRY_RUN" = "1" ] && exit 0
wait_until 60 "chrony synced to $INFRA_IP" sh -c "chronyc -n sources | grep -q '^\^\*.*${INFRA_IP}'"

sorted_scan=$(echo "$SCAN_IPS" | tr ' ' '\n' | sort | paste -sd' ')
check_eq "DNS: ${SCAN_NAME} = ${sorted_scan}" "$sorted_scan" sh -c "dig +short ${SCAN_NAME}.${LAB_DOMAIN} | sort | paste -sd' '"
check "DNS: PTR of ${NODE_IP}"                 sh -c "dig +short -x ${NODE_IP} | grep -q '^${NODE_NAME}\.${LAB_DOMAIN}\.$'"
for n in $RAC_NODES; do
    check "ping public ${n}"                   ping -c1 -W2 "$n"
    check "ping interconnect ${n}-priv"        ping -c1 -W2 "${n}-priv"
done
if [ ! -f /etc/oracle/olr.loc ]; then
    for ip in $SCAN_IPS $RAC_VIPS $OGG_VIP; do check "address free before GI: $ip" sh -c "! ping -c1 -W1 $ip"; done
fi
check "package oracle-ai-database-preinstall-26ai" rpm -q oracle-ai-database-preinstall-26ai
check "user grid in asmadmin"                  sh -c 'id -nG grid | grep -qw asmadmin'
check "user oracle in asmdba"                  sh -c 'id -nG oracle | grep -qw asmdba'
check "THP madvise"                            grep -q '\[madvise\]' /sys/kernel/mm/transparent_hugepage/enabled
check "firewalld off"                          sh -c "! systemctl is-active --quiet firewalld"
check "HugePages > 0"                          sh -c '[ "$(cat /proc/sys/vm/nr_hugepages)" -gt 0 ]'
check "NOZEROCONF=yes"                         grep -q '^NOZEROCONF=yes' /etc/sysconfig/network
check "kernel version-locked (ACFS, KB129209)" sh -c "dnf versionlock list 2>/dev/null | grep -q '^kernel'"
check "running kernel is a locked one"         sh -c "dnf versionlock list 2>/dev/null | grep -qF \"\$(uname -r | sed 's/\.x86_64$//')\""
check "RAM >= 8 GB"                            sh -c '[ "$(free -m | awk "/Mem/{print \$2}")" -ge 8000 ]'
check "/u01 free >= 40 GB (or GI already in)"  sh -c "[ -f /etc/oracle/olr.loc ] || [ \"\$(df -BG --output=avail /u01 | tail -1 | tr -dc 0-9)\" -ge 40 ]"
check "oraInst.loc absent or -> $INVENTORY"    sh -c "[ ! -f /etc/oraInst.loc ] || grep -q '$INVENTORY' /etc/oraInst.loc"
[ "$CHECK_FAILED" = "0" ] || die "OS prerequisites failed (CHECK FAIL above)"
mark_done rac_prereq
log "OS ready"
