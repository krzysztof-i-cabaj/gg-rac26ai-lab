#!/bin/bash
# ==============================================================================
# Tytul:        20_chrony.sh
# Opis:         Serwer czasu labu na gginfra: chrony bierze czas z puli przez NAT i udostepnia
#               go podsieci labu; "local stratum" trzyma czas takze bez internetu, zeby CTSS
#               i wezly RAC mialy jedno zrodlo. Powtarzalny.
# Description [EN]: Lab time server on gginfra: chrony syncs from the pool over NAT and serves
#               the lab subnet; "local stratum" keeps serving without internet so CTSS and the
#               RAC nodes share one source. Re-runnable.
#
# Autor:        KCB Kris
# Data:         2026-11-14
# Wersja:       1.0
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - OL9, chrony (kickstart), /root/lab/lab.env
# Requirements [EN]: - OL9, chrony (kickstart), /root/lab/lab.env
#
# Uzycie [PL]:       lab.cmd infra   (recznie: bash /root/lab/infra/20_chrony.sh)
# Usage [EN]:        lab.cmd infra   (manual: bash /root/lab/infra/20_chrony.sh)
# ==============================================================================
source /root/lab/lib.sh

CONF=/etc/chrony.d/lab-server.conf
mkdir -p /etc/chrony.d
grep -q '^include /etc/chrony.d/\*.conf' /etc/chrony.conf || \
    { grep -q '^confdir /etc/chrony.d' /etc/chrony.conf || run sh -c "echo 'include /etc/chrony.d/*.conf' >> /etc/chrony.conf"; }

log "chrony: serving time to $PUBLIC_SUBNET"
if write_if_changed "$CONF" <<EOF
# Lab NTP server (generated by 20_chrony.sh)
allow ${PUBLIC_SUBNET}
local stratum 8
EOF
then run systemctl restart chronyd; ok "chronyd restarted"; else ok "chrony config unchanged"; fi
run systemctl enable chronyd
mark_done infra_chrony
