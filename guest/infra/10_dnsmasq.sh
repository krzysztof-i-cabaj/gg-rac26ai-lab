# ==============================================================================
# Tytul:        10_dnsmasq.sh
# Opis:         DNS labu na gginfra: dnsmasq z rekordami z hosts.env (wezly, VIP, interconnect,
#               SCAN round-robin z 3 adresow, oggvip), PTR dla podsieci labu, reszta nazw do
#               resolvera NAT. Zapora: podsiec labu w strefie trusted. Powtarzalny.
# Description [EN]: Lab DNS on gginfra: dnsmasq serving hosts.env (nodes, VIPs, interconnect,
#               3-address round-robin SCAN, oggvip), PTR for the lab subnet, other names
#               forwarded to the NAT resolver. No firewalld in the lab. Re-runnable.
#
# Autor:        KCB Kris
# Data:         2026-11-15
# Wersja:       1.1 (bez firewalld / no firewalld)
# Konwencje:    <repo>/SETTINGS.md
#
# Wymagania [PL]:    - OL9, pakiet dnsmasq (kickstart role-infra), /root/lab/hosts.env
# Requirements [EN]: - OL9, dnsmasq package (role-infra kickstart), /root/lab/hosts.env
#
# Uzycie [PL]:       lab.cmd infra   (recznie: bash /root/lab/infra/10_dnsmasq.sh, DRY_RUN=1 = podglad)
# Usage [EN]:        lab.cmd infra   (manual: bash /root/lab/infra/10_dnsmasq.sh, DRY_RUN=1 = preview)
# ==============================================================================
source /root/lab/lib.sh

HOSTS_FILE=/etc/lab.hosts      # outside /etc/dnsmasq.d: every file there is parsed as config
CONF=/etc/dnsmasq.d/lab.conf
rev_zone=$(echo "${PUBLIC_SUBNET%/*}" | awk -F. '{print $3"."$2"."$1".in-addr.arpa"}')

log "dnsmasq: records from hosts.env -> $HOSTS_FILE"
changed=0
write_if_changed "$HOSTS_FILE" < "$LAB_DIR/hosts.env" && changed=1

write_if_changed "$CONF" <<EOF && changed=1
# Lab DNS for ${LAB_DOMAIN} (generated by 10_dnsmasq.sh)
domain-needed
bogus-priv
no-hosts
addn-hosts=${HOSTS_FILE}
domain=${LAB_DOMAIN}
local=/${LAB_DOMAIN}/
local=/${rev_zone}/
listen-address=127.0.0.1,${INFRA_IP}
bind-interfaces
# Upstream for everything else: the NAT resolver from /etc/resolv.conf
cache-size=1000
EOF

run systemctl enable --now dnsmasq
if [ "$changed" = "1" ]; then run systemctl restart dnsmasq; ok "dnsmasq restarted"; else ok "dnsmasq config unchanged"; fi

# Lab on a host-only network: no firewalld (RAC interconnect, SCAN, DNS, NTP between the VMs).
if systemctl is-enabled --quiet firewalld 2>/dev/null || systemctl is-active --quiet firewalld 2>/dev/null; then
    run systemctl disable --now firewalld
fi
ok "firewalld off (DNS 53, NTP 123 open to the lab)"
mark_done infra_dnsmasq
